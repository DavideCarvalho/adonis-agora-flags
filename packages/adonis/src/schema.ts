import { type Dialect, dialectOf, query, type SqlClient, type SqlDatabase } from './sql.js';

/**
 * Every table this package owns. Timestamps are BIGINT epoch milliseconds throughout (see
 * `toDate` in sql.ts), JSON is JSONB / JSON / TEXT depending on the dialect.
 */
export const FLAGS_TABLES = [
  'flags_environments',
  'flags_entities',
  'flags_audit',
  'flags_change_requests',
  'flags_schedules',
  'flags_usage',
  'flags_declarations',
  'flags_events',
  'flags_sink_cursors',
  'flags_exposures',
  'flags_tracks',
  'flags_results',
] as const;

export interface SchemaOptions {
  /**
   * Postgres only: partition `flags_events` by month on `ts`, so retention drops whole
   * partitions instead of deleting rows. Decide before the table exists — switching later needs a
   * manual migration. Default `false`.
   */
  partitionEvents?: boolean;
}

interface Types {
  json: string;
  bigintPk: string;
  double: string;
  text: string;
}

function typesFor(dialect: Dialect): Types {
  if (dialect === 'postgres') {
    return {
      json: 'JSONB',
      bigintPk: 'BIGINT GENERATED BY DEFAULT AS IDENTITY',
      double: 'DOUBLE PRECISION',
      text: 'TEXT',
    };
  }
  if (dialect === 'mysql') {
    return { json: 'JSON', bigintPk: 'BIGINT AUTO_INCREMENT', double: 'DOUBLE', text: 'TEXT' };
  }
  return { json: 'TEXT', bigintPk: 'INTEGER', double: 'REAL', text: 'TEXT' };
}

/** Variable-length keys stay ≤ 191 chars so MySQL utf8mb4 indexes fit. */
const K = 'VARCHAR(191)';

function statements(dialect: Dialect, options: SchemaOptions): string[] {
  const t = typesFor(dialect);
  const sqlite = dialect === 'sqlite';
  const eventsPk = sqlite
    ? 'id INTEGER PRIMARY KEY AUTOINCREMENT'
    : options.partitionEvents && dialect === 'postgres'
      ? `id ${t.bigintPk}`
      : `id ${t.bigintPk} PRIMARY KEY`;
  const eventsTail =
    options.partitionEvents && dialect === 'postgres'
      ? ', PRIMARY KEY (id, ts)) PARTITION BY RANGE (ts)'
      : ')';

  return [
    `CREATE TABLE IF NOT EXISTS flags_environments (
      name ${K} PRIMARY KEY,
      version BIGINT NOT NULL DEFAULT 0,
      updated_at BIGINT NOT NULL
    )`,
    `CREATE TABLE IF NOT EXISTS flags_entities (
      environment ${K} NOT NULL,
      entity VARCHAR(16) NOT NULL,
      entity_key ${K} NOT NULL,
      definition ${t.json} NOT NULL,
      updated_at BIGINT NOT NULL,
      updated_by ${K} NOT NULL,
      PRIMARY KEY (environment, entity, entity_key)
    )`,
    `CREATE TABLE IF NOT EXISTS flags_audit (
      id VARCHAR(36) PRIMARY KEY,
      environment ${K} NOT NULL,
      entity VARCHAR(16) NOT NULL,
      entity_key ${K} NULL,
      action VARCHAR(16) NOT NULL,
      before_value ${t.json} NULL,
      after_value ${t.json} NULL,
      actor_id ${K} NOT NULL,
      actor_name ${K} NULL,
      change_request_id VARCHAR(36) NULL,
      version BIGINT NOT NULL,
      at BIGINT NOT NULL
    )`,
    `CREATE TABLE IF NOT EXISTS flags_change_requests (
      id VARCHAR(36) PRIMARY KEY,
      environment ${K} NOT NULL,
      change_value ${t.json} NOT NULL,
      note ${t.text} NULL,
      requested_by ${t.json} NOT NULL,
      requested_at BIGINT NOT NULL,
      status VARCHAR(16) NOT NULL,
      reviewed_by ${t.json} NULL,
      reviewed_at BIGINT NULL,
      review_note ${t.text} NULL,
      base_version VARCHAR(32) NOT NULL
    )`,
    `CREATE TABLE IF NOT EXISTS flags_schedules (
      id VARCHAR(36) PRIMARY KEY,
      environment ${K} NOT NULL,
      flag ${K} NOT NULL,
      kind VARCHAR(16) NOT NULL,
      payload ${t.json} NOT NULL,
      run_at BIGINT NOT NULL,
      status VARCHAR(16) NOT NULL,
      created_by ${t.json} NOT NULL,
      error ${t.text} NULL,
      executed_at BIGINT NULL
    )`,
    `CREATE TABLE IF NOT EXISTS flags_usage (
      environment ${K} NOT NULL,
      flag ${K} NOT NULL,
      day CHAR(10) NOT NULL,
      evaluations BIGINT NOT NULL,
      PRIMARY KEY (environment, flag, day)
    )`,
    `CREATE TABLE IF NOT EXISTS flags_declarations (
      app ${K} NOT NULL,
      flag ${K} NOT NULL,
      declaration ${t.json} NOT NULL,
      last_seen_at BIGINT NOT NULL,
      PRIMARY KEY (app, flag)
    )`,
    `CREATE TABLE IF NOT EXISTS flags_events (
      ${eventsPk},
      event_id VARCHAR(36) NOT NULL,
      schema_version SMALLINT NOT NULL,
      app ${K} NOT NULL,
      environment VARCHAR(64) NOT NULL,
      type VARCHAR(16) NOT NULL,
      flag ${K} NULL,
      experiment ${K} NULL,
      variant ${K} NULL,
      name ${K} NULL,
      subject ${K} NOT NULL,
      subject_type VARCHAR(64) NOT NULL,
      value ${t.double} NULL,
      props ${t.json} NULL,
      ts BIGINT NOT NULL${
        dialect === 'postgres'
          ? `,
      tx xid8 NOT NULL DEFAULT pg_current_xact_id()`
          : ''
      }
    ${eventsTail}`,
    `CREATE TABLE IF NOT EXISTS flags_sink_cursors (
      sink ${K} PRIMARY KEY,
      last_id BIGINT NOT NULL DEFAULT 0,
      last_tx BIGINT NOT NULL DEFAULT 0,
      leased_by ${K} NULL,
      lease_until BIGINT NULL,
      delivered BIGINT NOT NULL DEFAULT 0,
      last_error ${t.text} NULL,
      updated_at BIGINT NOT NULL
    )`,
    `CREATE TABLE IF NOT EXISTS flags_exposures (
      environment VARCHAR(64) NOT NULL,
      experiment ${K} NOT NULL,
      subject ${K} NOT NULL,
      variant ${K} NOT NULL,
      flag ${K} NOT NULL,
      app ${K} NOT NULL,
      subject_type VARCHAR(64) NOT NULL,
      first_seen_ts BIGINT NOT NULL,
      PRIMARY KEY (environment, experiment, subject)
    )`,
    `CREATE TABLE IF NOT EXISTS flags_tracks (
      event_id VARCHAR(36) PRIMARY KEY,
      environment VARCHAR(64) NOT NULL,
      name ${K} NOT NULL,
      subject ${K} NOT NULL,
      subject_type VARCHAR(64) NOT NULL,
      app ${K} NOT NULL,
      value ${t.double} NULL,
      props ${t.json} NULL,
      ts BIGINT NOT NULL
    )`,
    `CREATE TABLE IF NOT EXISTS flags_results (
      environment VARCHAR(64) NOT NULL,
      experiment ${K} NOT NULL,
      payload ${t.json} NOT NULL,
      computed_at BIGINT NOT NULL,
      PRIMARY KEY (environment, experiment)
    )`,
  ];
}

const INDEXES: Array<[name: string, table: string, columns: string]> = [
  ['flags_audit_env_version_idx', 'flags_audit', 'environment, version'],
  ['flags_change_requests_status_idx', 'flags_change_requests', 'status, requested_at'],
  ['flags_schedules_due_idx', 'flags_schedules', 'status, run_at'],
  ['flags_events_ts_idx', 'flags_events', 'ts'],
  ['flags_exposures_subject_idx', 'flags_exposures', 'subject'],
  ['flags_tracks_env_name_subject_ts_idx', 'flags_tracks', 'environment, name, subject, ts'],
  ['flags_tracks_subject_idx', 'flags_tracks', 'subject'],
];

async function createIndex(
  client: SqlClient,
  dialect: Dialect,
  name: string,
  table: string,
  columns: string,
) {
  if (dialect !== 'mysql') {
    await client.rawQuery(`CREATE INDEX IF NOT EXISTS ${name} ON ${table} (${columns})`);
    return;
  }
  try {
    await client.rawQuery(`CREATE INDEX ${name} ON ${table} (${columns})`);
  } catch (error) {
    if (!/duplicate key name|already exists/i.test(String((error as Error).message))) throw error;
  }
}

/**
 * Serializes concurrent DDL across replicas booting together: a Postgres advisory lock or a MySQL
 * named lock. SQLite has a single writer already.
 */
async function withDdlLock<T>(
  db: SqlDatabase,
  dialect: Dialect,
  fn: (client: SqlClient) => Promise<T>,
) {
  if (dialect === 'postgres') {
    return db.transaction(async (trx) => {
      await trx.rawQuery("SELECT pg_advisory_xact_lock(hashtext('adonis-agora-flags-ddl'))");
      return fn(trx);
    });
  }
  if (dialect === 'mysql') {
    // GET_LOCK belongs to the session, so the lock, the DDL and the release must share one
    // connection: a transaction pins it. DDL commits implicitly, but the session (and the named
    // lock) survives that.
    return db.transaction(async (trx) => {
      await trx.rawQuery("SELECT GET_LOCK('adonis-agora-flags-ddl', 60)");
      try {
        return await fn(trx);
      } finally {
        await trx.rawQuery("SELECT RELEASE_LOCK('adonis-agora-flags-ddl')");
      }
    });
  }
  return fn(db);
}

/**
 * Creates every table and index. Idempotent and safe to run from several replicas at once. Called
 * by the provider at boot when `autoCreateSchema` is on (the default) and by the published
 * migration — the same function on both paths, so the schema cannot drift.
 */
export async function createFlagsTables(
  db: SqlDatabase,
  options: SchemaOptions = {},
): Promise<void> {
  const dialect = dialectOf(db);
  await withDdlLock(db, dialect, async (client) => {
    for (const sql of statements(dialect, options)) await client.rawQuery(sql);
    for (const [name, table, columns] of INDEXES) {
      // A BRIN index fits an append-only log ordered by time far better than a B-tree.
      if (name === 'flags_events_ts_idx' && dialect === 'postgres') {
        await client.rawQuery(
          `CREATE INDEX IF NOT EXISTS ${name} ON ${table} USING BRIN (${columns})`,
        );
        // The relay reads in (tx, id) order; see DbTransport.
        await client.rawQuery(
          'CREATE INDEX IF NOT EXISTS flags_events_tx_id_idx ON flags_events (tx, id)',
        );
        continue;
      }
      await createIndex(client, dialect, name, table, columns);
    }
  });
  if (options.partitionEvents && dialect === 'postgres')
    await ensureEventPartitions(db, Date.now());
}

/** Drops every table this package owns. */
export async function dropFlagsTables(db: SqlDatabase): Promise<void> {
  for (const table of [...FLAGS_TABLES].reverse())
    await db.rawQuery(`DROP TABLE IF EXISTS ${table}`);
}

/** Whether `flags_events` is a partitioned table (Postgres). */
export async function eventsArePartitioned(db: SqlClient): Promise<boolean> {
  if (dialectOf(db) !== 'postgres') return false;
  const rows = await query<{ relkind: string }>(
    db,
    "SELECT c.relkind FROM pg_class c WHERE c.relname = 'flags_events' AND c.relnamespace = to_regnamespace(current_schema())",
  );
  return rows[0]?.relkind === 'p';
}

function monthStart(ms: number, offset = 0): Date {
  const d = new Date(ms);
  return new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth() + offset, 1));
}

function partitionName(start: Date): string {
  return `flags_events_${start.getUTCFullYear()}${String(start.getUTCMonth() + 1).padStart(2, '0')}`;
}

/**
 * Creates the monthly partitions for the current and the next two months. Called at boot and by the
 * worker, so inserts never hit a missing partition.
 */
export async function ensureEventPartitions(db: SqlClient, now: number): Promise<void> {
  if (!(await eventsArePartitioned(db))) return;
  for (let offset = 0; offset < 3; offset++) {
    const start = monthStart(now, offset);
    const end = monthStart(now, offset + 1);
    await db.rawQuery(
      `CREATE TABLE IF NOT EXISTS ${partitionName(start)} PARTITION OF flags_events FOR VALUES FROM (${start.getTime()}) TO (${end.getTime()})`,
    );
  }
}

/**
 * Removes events older than `before` (epoch ms) that every sink cursor has already passed. On a
 * partitioned table whole monthly partitions are dropped; otherwise rows are deleted in batches.
 * Returns how many partitions or rows went away.
 */
export async function pruneEvents(
  db: SqlClient,
  before: number,
  safeId: number,
): Promise<{ partitions: number; rows: number }> {
  if (await eventsArePartitioned(db)) {
    const parts = await query<{ name: string; bound: string }>(
      db,
      `SELECT c.relname AS name, pg_get_expr(c.relpartbound, c.oid) AS bound
         FROM pg_inherits i JOIN pg_class c ON c.oid = i.inhrelid
         JOIN pg_class p ON p.oid = i.inhparent
        WHERE p.relname = 'flags_events' AND p.relnamespace = to_regnamespace(current_schema())`,
    );
    let partitions = 0;
    for (const part of parts) {
      const match = /TO \('?(\d+)'?\)/.exec(part.bound);
      if (!match || Number(match[1]) > before) continue;
      const maxRows = await query<{ max: string | number | null }>(
        db,
        `SELECT MAX(id) AS max FROM ${part.name}`,
      );
      const max = maxRows[0]?.max;
      if (max !== null && max !== undefined && Number(max) > safeId) continue;
      await db.rawQuery(`DROP TABLE ${part.name}`);
      partitions++;
    }
    return { partitions, rows: 0 };
  }
  const result = await query<{ count?: number }>(
    db,
    dialectOf(db) === 'postgres'
      ? 'WITH gone AS (DELETE FROM flags_events WHERE ts < ? AND id <= ? RETURNING 1) SELECT COUNT(*) AS count FROM gone'
      : 'DELETE FROM flags_events WHERE ts < ? AND id <= ?',
    [before, safeId],
  );
  return { partitions: 0, rows: Number(result[0]?.count ?? 0) };
}
