import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, join } from 'node:path';
import { flags } from '@adonisjs/core/ace';
import type { FlagDeclaration } from '../src/declare.js';
import { FlagsCommand } from './shared.js';

/** The TypeScript type a declaration's values have. */
function typeOf(declaration: FlagDeclaration): string {
  if (declaration.type === 'boolean') return 'boolean';
  if (declaration.type === 'number') return 'number';
  if (declaration.type === 'string') {
    return declaration.variants?.length
      ? declaration.variants.map((v) => JSON.stringify(v)).join(' | ')
      : 'string';
  }
  return 'JsonValue';
}

/**
 * The `.d.ts` for console-created flags. Code-declared flags are left to `InferFlags` in
 * `config/flags.ts` (their exact JSON types come from code). Exported for tests.
 */
export function renderFlagTypes(
  consoleFlags: Record<string, FlagDeclaration>,
  options: { strict: boolean },
): string {
  const entries = Object.keys(consoleFlags)
    .sort()
    .map((key) => {
      const declaration = consoleFlags[key]!;
      const doc = declaration.description
        ? `    /** ${declaration.description.replaceAll('*/', '* /')} */\n`
        : '';
      return `${doc}    ${JSON.stringify(key)}: ${typeOf(declaration)};`;
    })
    .join('\n');
  return `// Generated by \`node ace flags:types\` from the flags created in the console. Do not edit:
// regenerate after creating or changing a flag there.
import type { JsonValue } from '@adonis-agora/flags';

declare module '@adonis-agora/flags/types' {
  interface FlagsList {
${entries}
  }${
    options.strict
      ? `
  /** Every flag is now typed: unknown keys are compile errors. */
  interface FlagsSettings {
    strictKeys: true;
  }`
      : ''
  }
}
`;
}

export default class FlagsTypes extends FlagsCommand {
  static override commandName = 'flags:types';
  static override description = 'Generate TypeScript types for the flags created in the console';

  @flags.string({ description: 'Environment to read (default: the configured one)' })
  declare env?: string;

  @flags.string({ description: 'Output file (default: types/flags.d.ts)' })
  declare out?: string;

  @flags.boolean({
    description: 'Make unknown flag keys a compile error (default: true)',
    default: true,
  })
  declare strict: boolean;

  override async run() {
    const runtime = await this.runtime();
    const environment = this.env ?? runtime.manager.environment;
    const ruleset = await runtime.store!.readRuleset(environment);
    const code = runtime.manager.declarations;
    const consoleFlags: Record<string, FlagDeclaration> = {};
    for (const [key, definition] of Object.entries(ruleset.flags)) {
      if (definition.declaration && !code[key]) consoleFlags[key] = { ...definition.declaration };
    }
    const target = this.out ?? 'types/flags.d.ts';
    const path = isAbsolute(target) ? target : join(this.app.appRoot.pathname, target);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, renderFlagTypes(consoleFlags, { strict: this.strict }));
    this.logger.success(
      `${Object.keys(consoleFlags).length} console flag(s) typed in ${target}${this.strict ? ' (strict keys)' : ''}`,
    );
  }
}
